type Tier = "entry" | "mid" | "premium" | "luxury";

function features(tier: Tier, opts: { ev?: boolean; adas?: boolean; extra?: Partial<Record<FeatureGroup["group"], string[]>> } = {}): FeatureGroup[] {
  const rank = { entry: 0, mid: 1, premium: 2, luxury: 3 }[tier];
  const pick = (levels: string[][]) => levels.slice(0, rank + 1).flat();

  const groups: FeatureGroup[] = [
    {
      group: "Comfort",
      items: pick([
        ["Automatic climate control", "Rear AC vents", "Keyless entry & push-button start", "Height-adjustable driver seat"],
        ["Cruise control", "Wireless phone charger", "Electric sunroof"],
        ["Ventilated front seats", "Powered driver seat with memory", "Panoramic sunroof"],
        ["Four-zone climate control", "Massage function, front & rear", "Soft-close doors", "Adaptive air suspension"],
      ]),
    },
    {
      group: "Infotainment",
      items: pick([
        ["Touchscreen infotainment", "Wireless Android Auto & Apple CarPlay", "Steering-mounted controls"],
        ["10.25-inch HD touchscreen", "Fully digital driver display", "Connected-car app with remote functions"],
        ["Premium surround audio", "Over-the-air software updates", "Head-up display"],
        ["Rear-seat entertainment screens", "3D surround sound with 20+ speakers", "Augmented-reality navigation"],
      ]),
    },
    {
      group: "Safety",
      items: [
        ...pick([
          ["6 airbags", "ABS with EBD", "Electronic stability control", "ISOFIX child-seat mounts", "Hill-hold assist", "Rear parking camera"],
          ["Tyre-pressure monitoring", "Front parking sensors"],
          ["360° surround camera", "Blind-spot monitoring"],
          ["Night vision assist", "Pre-collision occupant protection"],
        ]),
        ...(opts.adas || rank >= 2 ? ["Level 2 ADAS (adaptive cruise, lane-keep, AEB)"] : []),
      ],
    },
    {
      group: "Exterior",
      items: pick([
        ["LED headlamps with DRLs", "Alloy wheels", "Body-coloured door handles"],
        ["Connected LED tail-lamps", "Shark-fin antenna", "Rain-sensing wipers"],
        ["Adaptive LED matrix headlamps", "18-inch machined alloys", "Puddle lamps"],
        ["Laser / digital light headlamps", "20-inch forged wheels", "Illuminated grille"],
      ]),
    },
    {
      group: "Interior",
      items: pick([
        ["Dual-tone dashboard", "Fabric upholstery", "Rear centre armrest"],
        ["Leatherette upholstery", "Ambient lighting", "Rear sunshades"],
        ["Ventilated leather seats", "64-colour ambient lighting", "Open-pore wood trim"],
        ["Nappa leather throughout", "Executive rear seats with leg rest", "Heated & cooled cupholders"],
      ]),
    },
  ];

  if (opts.ev) {
    groups.push({
      group: "Performance",
      items: ["Single-pedal driving", "Multi-level regenerative braking", "Vehicle-to-load (V2L) power outlet", "Battery pre-conditioning for fast charging"],
    });
  }

  if (opts.extra) {
    for (const [group, items] of Object.entries(opts.extra)) {
      const target = groups.find((g) => g.group === group);
      if (target && items) target.items.unshift(...items);
      else if (items) groups.push({ group: group as FeatureGroup["group"], items });
    }
  }
  return groups;
}

